export interface WeeklyDigestData {
  userName: string;
  startDate: string;
  endDate: string;
  tasksCompleted: number;
  hoursSaved: string;
  learningProgress: string;
  dashboardUrl: string;
  locale?: "es" | "en";
}

export function renderWeeklyDigestEmail(data: WeeklyDigestData): { html: string; text: string } {
  const isEs = data.locale !== "en";
  const title = isEs ? "Tu resumen semanal de CELAEST" : "Your CELAEST Weekly Summary";
  const subtitle = `${data.startDate} &ndash; ${data.endDate}`;
  const intro = isEs
    ? "Aquí tienes el impacto y avance que generaron tus sistemas y herramientas de CELAEST durante la última semana:"
    : "Here is the tangible impact and progress generated by your CELAEST systems over the past week:";
  const buttonText = isEs ? "Ir al Dashboard" : "Open Dashboard";

  const text = `Hola, ${data.userName}

${title} (${data.startDate} - ${data.endDate})

${intro}
- Tareas Automatizadas: ${data.tasksCompleted} ejecuciones
- Tiempo Estimado Ahorrado: ${data.hoursSaved} horas
- Progreso de Aprendizaje/Dominio: ${data.learningProgress}

Continúa optimizando en: ${data.dashboardUrl}

---
CELAEST Inc. · Resumen Semanal Automatizado`;

  const html = `<!DOCTYPE html>
<html lang="${isEs ? "es" : "en"}">
<head>
  <meta charset="utf-8">
  <title>${title}</title>
  <style>
    body { margin: 0; padding: 0; background: #050508; color: #E2E8F0; font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; }
    .container { max-width: 580px; margin: 40px auto; background: #0B0B14; border: 1px solid rgba(255, 255, 255, 0.08); border-radius: 16px; overflow: hidden; }
    .header { padding: 32px 36px 20px; background: linear-gradient(180deg, rgba(124, 58, 237, 0.16) 0%, rgba(11, 11, 20, 0) 100%); border-bottom: 1px solid rgba(255, 255, 255, 0.06); }
    .logo { font-size: 20px; font-weight: 800; letter-spacing: 0.18em; color: #FFFFFF; }
    .content { padding: 36px 36px 28px; }
    h1 { font-size: 22px; font-weight: 700; color: #FFFFFF; margin: 0 0 4px; }
    .subtitle { font-size: 13px; color: #A855F7; margin-bottom: 20px; }
    .grid { display: grid; grid-template-columns: 1fr 1fr; gap: 12px; margin: 24px 0; }
    .metric-card { background: rgba(255, 255, 255, 0.03); border: 1px solid rgba(255, 255, 255, 0.08); border-radius: 10px; padding: 18px; text-align: center; }
    .metric-num { font-size: 28px; font-weight: 800; color: #FFFFFF; margin-bottom: 4px; }
    .metric-label { font-size: 11px; text-transform: uppercase; color: #64748B; font-weight: 600; }
    .btn { display: inline-block; background: linear-gradient(135deg, #7C3AED 0%, #9333EA 100%); color: #FFFFFF !important; font-weight: 600; font-size: 14px; padding: 12px 28px; border-radius: 8px; text-decoration: none; }
    .footer { padding: 20px 36px; background: #08080E; border-top: 1px solid rgba(255, 255, 255, 0.05); font-size: 12px; color: #64748B; text-align: center; }
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <div class="logo">CELAEST</div>
    </div>
    <div class="content">
      <h1>${title}</h1>
      <div class="subtitle">${subtitle}</div>
      <p style="color: #F8FAFC; font-weight: 600;">Hola, ${data.userName}</p>
      <p style="color: #94A3B8; font-size: 14px; line-height: 1.6;">${intro}</p>

      <div class="grid">
        <div class="metric-card">
          <div class="metric-num" style="color: #A855F7;">${data.tasksCompleted}</div>
          <div class="metric-label">${isEs ? "Tareas Ejecutadas" : "Tasks Executed"}</div>
        </div>
        <div class="metric-card">
          <div class="metric-num" style="color: #22C55E;">${data.hoursSaved}h</div>
          <div class="metric-label">${isEs ? "Tiempo Ahorrado" : "Hours Saved"}</div>
        </div>
      </div>

      <div style="background: rgba(255, 255, 255, 0.02); border: 1px solid rgba(255, 255, 255, 0.06); border-radius: 10px; padding: 14px 18px; margin-bottom: 24px; font-size: 13px; color: #CBD5E1;">
        <strong style="color: #F8FAFC;">${isEs ? "Hito de Dominio:" : "Domain Milestone:"}</strong> ${data.learningProgress}
      </div>

      <div style="text-align: center;">
        <a href="${data.dashboardUrl}" class="btn">${buttonText} &rarr;</a>
      </div>
    </div>
    <div class="footer">
      &copy; ${new Date().getFullYear()} CELAEST Inc. &middot; Resumen Semanal
    </div>
  </div>
</body>
</html>`;

  return { html, text };
}
